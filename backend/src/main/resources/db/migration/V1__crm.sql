CREATE TABLE app_users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(254) NOT NULL UNIQUE,
  password_hash VARCHAR(100) NOT NULL
);
-- Transitional payload preserves every legacy field while typed entities are extracted.
CREATE TABLE crm_records (
  id VARCHAR(36) PRIMARY KEY,
  module VARCHAR(30) NOT NULL,
  legacy_id VARCHAR(100),
  payload JSONB NOT NULL,
  vehicle_id VARCHAR(36) REFERENCES crm_records(id),
  version BIGINT NOT NULL DEFAULT 0,
  UNIQUE(module, legacy_id)
);
CREATE INDEX idx_records_module ON crm_records(module);
CREATE INDEX idx_records_vehicle ON crm_records(vehicle_id);
